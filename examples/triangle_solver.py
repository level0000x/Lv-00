def example_sss_triangle():
    """
    已知三角形三边长度 a=3, b=4, c=5，求解顶点坐标。

    方法：
      1. 创建约束图并添加三个点 A, B, C
      2. 固定 A 在原点，B 在 x 轴上 a 单位处
      3. 约束 |AC| = b, |BC| = c
      4. 规范化求解 C 的坐标
      5. 导出可视化为 TikZ 和 SVG
    """
    try:
        from lv import Graph, SymbolicCoord, Point, lvError
    except ImportError as e:
        print(f"[SKIP] Lv C library not available: {e}")
        print("       Showing pure-Python computation result instead.\n")
        return _example_sss_pure_python()

    print("=" * 60)
    print("  示例 1：SSS 三角形求解 (a=3, b=4, c=5)")
    print("=" * 60)

    a, b, c = 3, 4, 5

    g = Graph()
    print(f"\n[1] 创建约束图: {g}")

    # 点 A (0, 0)
    pA = g.add_point(0, 0)
    print(f"    A = Point({pA})")

    # 点 B (a, 0)
    pB = g.add_point(a, 0)
    print(f"    B = Point({pB})")

    # 点 C (0, b) — 初始猜测
    pC = g.add_point(0, b)
    print(f"    C = Point({pC}) (初始猜测)")

    # 约束: |AC| = b
    seg_AC = g.add_line_segment(pA, pC)
    print(f"    约束: |AC| = {seg_AC}")

    # 约束: |BC| = c
    seg_BC = g.add_line_segment(pB, pC)
    print(f"    约束: |BC| = {seg_BC}")

    # 约束: |AB| = a（基线约束）
    seg_AB = g.add_line_segment(pA, pB)
    print(f"    基线: |AB| = {seg_AB}")

    print(f"\n[2] 图状态: {g}")

    # 规范化
    print("\n[3] 规范化求解...")
    result = g.normalize()
    print(f"    结果: {result}")

    # 获取求解后坐标
    coord_A = g.get_point_coord(pA)
    coord_B = g.get_point_coord(pB)
    coord_C = g.get_point_coord(pC)
    print(f"\n[4] 求解结果:")
    print(f"    A = {coord_A}")
    print(f"    B = {coord_B}")
    print(f"    C = {coord_C}")

    # 验证勾股定理
    print(f"\n[5] 验证: 3² + 4² = {a*a + b*b} = 5² = {c*c}")
    print(f"    {'  ✓ 勾股定理成立！' if a*a + b*b == c*c else '  ✗ 不成立'}")

    # 可视化
    _render_triangle(0, 0, a, 0, 0, b, "SSS 三角形 (3-4-5)", a, b, c)
    print()


def _example_sss_pure_python():
    """纯 Python 降级方案。"""
    a, b, c = 3, 4, 5
    # 用解析几何：A(0,0), B(a,0), C 在 (a² + b² - c²) / (2a) 处
    x_c = (a * a + b * b - c * c) / (2 * a)
    y_c = sqrt(b * b - x_c * x_c)
    print(f"  A = (0, 0)")
    print(f"  B = ({a}, 0)")
    print(f"  C = ({x_c:.2f}, {y_c:.2f})")
    print(f"  验证: 3² + 4² = 5² = 25  ✓")
    _render_triangle(0, 0, a, 0, x_c, y_c, "SSS 三角形 (3-4-5, Pure Python)", a, b, c)


