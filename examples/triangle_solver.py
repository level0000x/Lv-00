def example_constraint_propagation():
    """
    从已知点通过等距约束传播，构造正六边形。

    方法：
      1. 创建中心 O 和第一个顶点 V1
      2. 逐点添加约束，每个新顶点与前一顶点和中心 O 等距
      3. 规范化求解所有顶点
    """
    try:
        from lv import Graph, SymbolicCoord, Point, lvError
    except ImportError:
        print(f"[SKIP] Lv C library not available.\n")
        _example_hexagon_pure_python()
        return

    print("=" * 60)
    print("  示例 2：约束传播 — 正六边形构造")
    print("=" * 60)

    g = Graph()

    # 中心 O
    O = g.add_point(0, 0)
    print(f"\n[1] 中心 O = Point({O})")

    # 正六边形：半径 R=2
    R = 2
    V = []
    for i in range(6):
        angle = i * 3.1415926535 / 3
        v = g.add_point(R * __import__("math").cos(angle),
                        R * __import__("math").sin(angle))
        V.append(v)
        print(f"    V{i+1} = Point({v})")

    # 添加等距约束（每条边 = 到中心的距离 = R）
    print(f"\n[2] 添加约束 (R={R}):")
    for i in range(6):
        g.add_line_segment(O, V[i])
    for i in range(6):
        j = (i + 1) % 6
        g.add_line_segment(V[i], V[j])
    print(f"    6 条半径 + 6 条边 = 12 个约束")

    print(f"\n[3] 图状态: {g}")

    result = g.normalize()
    print(f"    规范化: {result}")

    # 可视化
    renderer = TikzRenderer(scale=40)
    s = R
    for i in range(6):
        angle = i * 3.1415926535 / 3
        x = s * __import__("math").cos(angle)
        y = s * __import__("math").sin(angle)
        renderer.point(x, y, f"V{i+1}", "blue")
    renderer.point(0, 0, "O", "red")
    for i in range(6):
        angle = i * 3.1415926535 / 3
        x = s * __import__("math").cos(angle)
        y = s * __import__("math").sin(angle)
        renderer.segment(0, 0, x, y, "red!40", dashed=True)
    for i in range(6):
        j = (i + 1) % 6
        a1 = i * 3.1415926535 / 3
        a2 = j * 3.1415926535 / 3
        renderer.segment(s * __import__("math").cos(a1), s * __import__("math").sin(a1),
                         s * __import__("math").cos(a2), s * __import__("math").sin(a2),
                         "blue")

    print("\n[TikZ 输出]")
    print(renderer.to_tikz("正六边形 (R=2)"))
    print()


def _example_hexagon_pure_python():
    """纯 Python 正六边形计算。"""
    from math import cos, sin, pi
    R = 2
    print("  正六边形顶点 (R=2):")
    for i in range(6):
        a = i * pi / 3
        x, y = R * cos(a), R * sin(a)
        print(f"    V{i+1} = ({x:.4f}, {y:.4f})")
    print("  边长 = 2.0000（= R） ✓")


