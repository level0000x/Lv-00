def _render_triangle(ax, ay, bx, by, cx, cy, title, a, b, c):
    """渲染三角形为 TikZ 和 SVG 并输出到文件。"""
    # TikZ
    tikz = TikzRenderer(scale=60)
    tikz.point(ax, ay, "A", "red", 3)
    tikz.point(bx, by, "B", "blue", 3)
    tikz.point(cx, cy, "C", "green!60!black", 3)
    tikz.segment(ax, ay, bx, by, "black", label=f"c={c}")
    tikz.segment(bx, by, cx, cy, "black", label=f"a={a}")
    tikz.segment(cx, cy, ax, ay, "black", label=f"b={b}")
    tikz.angle_mark(ax, ay, bx, by, cx, cy, 0.7, "?")

    out_dir = os.path.dirname(__file__)
    tikz_path = os.path.join(out_dir, "triangle_output.tex")
    with open(tikz_path, "w", encoding="utf-8") as f:
        f.write(tikz.to_tikz(f"Triangle: {title}"))
    print(f"  TikZ 导出 → {tikz_path}")

    # SVG
    svg = SvgRenderer(400, 400)
    svg.point(ax, ay, "A", "#cc0000")
    svg.point(bx, by, "B", "#0066cc")
    svg.point(cx, cy, "C", "#228b22")
    svg.segment(ax, ay, bx, by, "#333", label=f"c={c}")
    svg.segment(bx, by, cx, cy, "#333", label=f"a={a}")
    svg.segment(cx, cy, ax, ay, "#333", label=f"b={b}")

    svg_path = os.path.join(out_dir, "triangle_output.svg")
    with open(svg_path, "w", encoding="utf-8") as f:
        f.write(svg.to_svg(title))
    print(f"  SVG 导出 → {svg_path}")


