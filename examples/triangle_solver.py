class TikzRenderer:
    """生成 LaTeX TikZ 代码的轻量渲染器。

    支持点（填充圆）、线段（draw）、标注文本（node）。
    输出可直接嵌入 LaTeX 文档，无需额外宏包。
    """

    def __init__(self, scale: float = 1.0):
        self._lines: list[str] = []
        self._scale = scale

    def point(self, x: float, y: float, label: str = "", color: str = "black", radius: float = 2.0):
        """绘制一个实心点，可选标签。"""
        self._lines.append(
            f"  \\fill[{color}] ({x * self._scale:.2f},{y * self._scale:.2f}) "
            f"circle ({radius}pt);"
        )
        if label:
            offset = 0.3 * self._scale
            self._lines.append(
                f"  \\node[above right,font=\\footnotesize] "
                f"at ({x * self._scale:.2f},{y * self._scale:.2f}) {{{label}}};"
            )

    def segment(self, x1: float, y1: float, x2: float, y2: float,
                color: str = "black", dashed: bool = False, label: str = ""):
        """绘制线段。"""
        dash = ", dashed" if dashed else ""
        self._lines.append(
            f"  \\draw[{color}{dash}, line width=0.5pt] "
            f"({x1 * self._scale:.2f},{y1 * self._scale:.2f}) -- "
            f"({x2 * self._scale:.2f},{y2 * self._scale:.2f});"
        )
        if label:
            mx = (x1 + x2) / 2 * self._scale
            my = (y1 + y2) / 2 * self._scale
            self._lines.append(
                f"  \\node[font=\\footnotesize,fill=white,inner sep=1pt] "
                f"at ({mx:.2f},{my:.2f}) {{{label}}};"
            )

    def angle_mark(self, vertex_x: float, vertex_y: float,
                   p1_x: float, p1_y: float, p2_x: float, p2_y: float,
                   radius: float = 0.5, label: str = ""):
        """在顶点处绘制角度标记弧。"""
        from math import atan2
        a1 = atan2(p1_y - vertex_y, p1_x - vertex_x)
        a2 = atan2(p2_y - vertex_y, p2_x - vertex_x)
        a1_d = a1 * 180 / 3.1415926535
        a2_d = a2 * 180 / 3.1415926535
        # 确保短弧
        if a2_d < a1_d:
            a2_d += 360
        if a2_d - a1_d > 180:
            a2_d, a1_d = a1_d, a2_d
        s = self._scale
        self._lines.append(
            f"  \\draw ({vertex_x * s:.2f},{vertex_y * s:.2f}) "
            f"++({a1_d:.1f}:{radius * s:.2f}) arc "
            f"({a1_d:.1f}:{a2_d:.1f}:{radius * s:.2f});"
        )
        if label:
            mid_a = (a1 + a2) / 2
            mx = vertex_x + radius * 1.4 * __import__("math").cos(mid_a)
            my = vertex_y + radius * 1.4 * __import__("math").sin(mid_a)
            self._lines.append(
                f"  \\node[font=\\footnotesize] at ({mx * s:.2f},{my * s:.2f}) {{{label}}};"
            )

    def to_tikz(self, caption: str = "") -> str:
        """输出完整 TikZ 代码。"""
        header = "% Generated by Lv Triangle Solver\n"
        header += "\\begin{tikzpicture}[scale=1.0]\n"
        if caption:
            header += f"  %% {caption}\n"
        body = "\n".join(self._lines)
        footer = "\n\\end{tikzpicture}"
        return header + body + footer


class SvgRenderer:
    """生成 SVG 矢量图的轻量渲染器。

    输出标准 SVG 1.1，可在浏览器中直接打开。
    """

    def __init__(self, width: int = 400, height: int = 400, pad: float = 20.0):
        self._elements: list[str] = []
        self._w = width
        self._h = height
        self._pad = pad
        self._xmin = float("inf")
        self._xmax = float("-inf")
        self._ymin = float("inf")
        self._ymax = float("-inf")

    def _track_bounds(self, x: float, y: float):
        self._xmin = min(self._xmin, x)
        self._xmax = max(self._xmax, x)
        self._ymin = min(self._ymin, y)
        self._ymax = max(self._ymax, y)

    def _transform(self, x: float, y: float) -> tuple[float, float]:
        """世界坐标 → SVG 画布坐标。Y 轴翻转（SVG Y 向下）。"""
        bw = self._xmax - self._xmin or 1.0
        bh = self._ymax - self._ymin or 1.0
        scale = min((self._w - 2 * self._pad) / bw, (self._h - 2 * self._pad) / bh)
        sx = self._pad + (x - self._xmin) * scale
        sy = self._h - self._pad - (y - self._ymin) * scale  # Y 翻转
        return sx, sy

    def point(self, x: float, y: float, label: str = "", color: str = "#000000", r: float = 3.0):
        self._track_bounds(x, y)
        sx, sy = self._transform(x, y)
        fill = color if color.startswith("#") else "#000000"
        self._elements.append(
            f'  <circle cx="{sx:.1f}" cy="{sy:.1f}" r="{r}" fill="{fill}"/>'
        )
        if label:
            self._elements.append(
                f'  <text x="{sx + r + 3:.1f}" y="{sy - r - 3:.1f}" '
                f'font-size="11" fill="#333">{label}</text>'
            )

    def segment(self, x1: float, y1: float, x2: float, y2: float,
                color: str = "#333", dashed: bool = False, label: str = ""):
        self._track_bounds(x1, y1)
        self._track_bounds(x2, y2)
        sx1, sy1 = self._transform(x1, y1)
        sx2, sy2 = self._transform(x2, y2)
        dash = ' stroke-dasharray="5,5"' if dashed else ""
        self._elements.append(
            f'  <line x1="{sx1:.1f}" y1="{sy1:.1f}" x2="{sx2:.1f}" y2="{sy2:.1f}" '
            f'stroke="{color}" stroke-width="1" opacity="0.8"{dash}/>'
        )
        if label:
            smx = (sx1 + sx2) / 2
            smy = (sy1 + sy2) / 2
            self._elements.append(
                f'  <text x="{smx:.1f}" y="{smy:.1f}" '
                f'font-size="10" fill="#555" text-anchor="middle">{label}</text>'
            )

    def to_svg(self, caption: str = "") -> str:
        lines = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            f'<svg xmlns="http://www.w3.org/2000/svg" '
            f'width="{self._w}" height="{self._h}" '
            f'viewBox="0 0 {self._w} {self._h}">',
            f'  <!-- {caption} -->' if caption else "",
            f'  <rect width="100%" height="100%" fill="#fafafa"/>',
        ]
        lines.extend(self._elements)
        lines.append("</svg>")
        return "\n".join(l for l in lines if l)


