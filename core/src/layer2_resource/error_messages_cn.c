/* ============================================================
 * 公共API实现
 * ============================================================ */

/**
 * @brief 获取错误码对应的中文错误信息
 */
const char *lv00_error_string_cn(Lv00ErrorCode code) {
    if (code >= 0 && code < LV00_ERROR_COUNT) {
        return g_error_string_cn[code];
    }
    return "未知错误码";
}

/**
 * @brief 获取错误码的中文简称
 */
const char *lv00_error_name_cn(Lv00ErrorCode code) {
    if (code >= 0 && code < LV00_ERROR_COUNT) {
        return g_error_name_cn[code];
    }
    return "未知错误";
}

/**
 * @brief 获取错误码所属的中文错误类别
 */
const char *lv00_error_category_cn(Lv00ErrorCode code) {
    if (code >= 0 && code < LV00_ERROR_COUNT) {
        return g_error_category_cn[code];
    }
    return "未知类别";
}

/**
 * @brief 获取完整的中文错误描述
 */
int lv00_get_error_description_cn(Lv00ErrorCode code, char *buf, size_t buf_size) {
    if (!buf || buf_size == 0)
        return -1;

    const char *category = lv00_error_category_cn(code);
    const char *name = lv00_error_name_cn(code);
    const char *detail = lv00_error_string_cn(code);

    return snprintf(buf, buf_size, "[%s] %s：%s", category, name, detail);
}

/**
 * @brief 获取当前线程的最后错误的中文描述
 */
int lv00_get_last_error_description_cn(char *buf, size_t buf_size) {
    Lv00ErrorCode code = lv00_get_last_error_code();
    int len = lv00_get_error_description_cn(code, buf, buf_size);

    if (len > 0 && len < (int)buf_size) {
        const char *msg = lv00_get_last_error_message();
        if (msg && msg[0] != '\0') {
            int remaining = (int)buf_size - len - 1;
            if (remaining > 0) {
                snprintf(buf + len, (size_t)remaining, "（%s）", msg);
            }
        }
    }

    return len;
}
